<#
.SYNOPSIS
    Generates the standalone Markdown table of contents from BOOK_PLAN.md.
.PARAMETER Check
    Verifies that the generated contents file is current without writing it.
#>
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$planPath = Join-Path $root 'BOOK_PLAN.md'
$outputPath = Join-Path $root '26_Appendices_and_Glossary/CH05_Combined_Table_of_Contents.md'
$plan = Get-Content -Path $planPath -Raw -Encoding UTF8
$partRows = [regex]::Matches(
    $plan,
    '(?m)^\|\s*(\d{2})\s*\|\s*\[([^\]]+)\]\(([^)]+PART_OVERVIEW\.md)\)'
)

if ($partRows.Count -ne 26) {
    throw "Expected 26 part rows in BOOK_PLAN.md; found $($partRows.Count)."
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('<!-- Generated by scripts/generate-combined-toc.ps1 from BOOK_PLAN.md and chapter headings. Do not edit by hand. -->')
$lines.Add('# Combined Table of Contents')
$lines.Add('')
$lines.Add('This standalone Markdown navigation page follows the part order in [BOOK_PLAN.md](../BOOK_PLAN.md) and chapter filename order used by [build-book.ps1](../scripts/build-book.ps1). Part overviews remain the source for chapter summaries and status. The PDF and EPUB builds also generate their own heading-based contents with Pandoc.')
$lines.Add('')
$lines.Add('Generated content boundary: part order and part links come from `BOOK_PLAN.md`; chapter links and labels come from chapter files and their first level-one headings. Update those sources, then run `scripts/generate-combined-toc.ps1`.')
$lines.Add('')
$chapterCount = 0

foreach ($row in $partRows) {
    $partId = $row.Groups[1].Value
    $partTitle = $row.Groups[2].Value
    $overviewLink = $row.Groups[3].Value -replace '\\', '/'
    $partFolder = Split-Path -Parent $overviewLink
    $partPath = Join-Path $root ($partFolder -replace '/', '\')
    if (-not (Test-Path (Join-Path $partPath 'PART_OVERVIEW.md'))) {
        throw "Missing part overview for Part $partId at $overviewLink."
    }

    $partLink = "../$overviewLink"
    $lines.Add('')
    $lines.Add("## Part $partId - [$partTitle]($partLink)")
    $lines.Add('')

    $chapters = @(Get-ChildItem -Path $partPath -Filter 'CH*.md' -File | Sort-Object Name)
    foreach ($chapter in $chapters) {
        $text = Get-Content -Path $chapter.FullName -Raw -Encoding UTF8
        if ($text -notmatch '(?m)^#\s+(.+?)\s*$') {
            throw "Chapter has no level-one title: $($chapter.FullName)"
        }
        $title = $Matches[1]
        $relativePath = "../$partFolder/$($chapter.Name)"
        $lines.Add("- [$title]($relativePath)")
        $chapterCount++
    }
}

$lines.Add('')
$lines.Add('## Navigation Model')
$lines.Add('')
$lines.Add('The hierarchy below distinguishes book order, part overviews, chapter files, and in-chapter anchors. Chapter titles link to their source files; heading anchors remain owned by those files and may change when headings change.')
$lines.Add('')
$lines.Add('```mermaid')
$lines.Add('flowchart TD')
$lines.Add('    Book[Handbook] --> Foundations[Foundations and core disciplines]')
$lines.Add('    Book --> Platforms[Cloud, delivery, and platform practice]')
$lines.Add('    Book --> Architecture[Architecture methods and cases]')
$lines.Add('    Book --> References[Appendices and indexes]')
$lines.Add('    Foundations --> PartOverview[Part overview]')
$lines.Add('    Platforms --> PartOverview')
$lines.Add('    Architecture --> PartOverview')
$lines.Add('    References --> PartOverview')
$lines.Add('    PartOverview --> Chapter[Chapter file]')
$lines.Add('    Chapter --> Heading[Heading anchor]')
$lines.Add('```')
$lines.Add('')
$lines.Add('```mermaid')
$lines.Add('flowchart LR')
$lines.Add('    OrderedParts[BOOK_PLAN reading order] --> Part[Part overview]')
$lines.Add('    Part --> Chapter[Sorted chapter files]')
$lines.Add('    Chapter --> Next[Next chapter in reading sequence]')
$lines.Add('    Next --> Next')
$lines.Add('```')
$lines.Add('')
$lines.Add('```mermaid')
$lines.Add('flowchart LR')
$lines.Add('    PartLink[Part link] --> Overview[PART_OVERVIEW.md]')
$lines.Add('    Overview --> ChapterLink[Chapter file link]')
$lines.Add('    ChapterLink --> HeadingLink[Stable heading anchor]')
$lines.Add('    SourceHeading[Chapter level-one heading] --> Label[Generated chapter label]')
$lines.Add('    Label --> ChapterLink')
$lines.Add('```')
$lines.Add('')
$lines.Add('```mermaid')
$lines.Add('flowchart LR')
$lines.Add('    Plan[BOOK_PLAN.md] --> Generator[Combined contents generator]')
$lines.Add('    ChapterFiles[Chapter filenames and headings] --> Generator')
$lines.Add('    Generator --> Markdown[Standalone combined contents]')
$lines.Add('    Markdown --> Reader[Markdown navigation]')
$lines.Add('    BuildScript[build-book.ps1] --> Pandoc[Pandoc heading-based TOC]')
$lines.Add('    ChapterFiles --> Pandoc')
$lines.Add('```')
$lines.Add('')
$lines.Add('```mermaid')
$lines.Add('flowchart TD')
$lines.Add('    Sources[Plan, overviews, and chapter files] --> Generate[Regenerate contents]')
$lines.Add('    Generate --> Links[Validate every local link]')
$lines.Add('    Links --> Counts[Compare chapter and part counts]')
$lines.Add('    Counts --> Diff[Check generated-file drift]')
$lines.Add('    Diff -->|Clean| Publish[Commit source and generated artifact together]')
$lines.Add('    Diff -->|Changed| Generate')
$lines.Add('```')
$lines.Add('')
$lines.Add("The generator found $chapterCount chapter files across 26 parts. Run it with `-Check` in validation to detect stale generated output.")
$lines.Add('')
$generated = ($lines -join "`n") + "`n"

if ($Check) {
    if (-not (Test-Path $outputPath)) {
        throw "Generated contents file is missing: $outputPath"
    }
    $existing = [IO.File]::ReadAllText($outputPath)
    if ($existing -cne $generated) {
        throw 'Combined contents are stale. Run scripts/generate-combined-toc.ps1 to regenerate.'
    }
    Write-Output "Combined contents are current: 26 parts, $chapterCount chapters."
    exit 0
}

[IO.File]::WriteAllText($outputPath, $generated, [Text.UTF8Encoding]::new($false))
Write-Output "Generated $outputPath with 26 parts and $chapterCount chapters."